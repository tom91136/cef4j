package net.kurobako.cef4j.codegen.ipc

import net.kurobako.cef4j.codegen.Banners
import net.kurobako.cef4j.codegen.Naming

object JavaFacadeEmitter {

  def baseName(affinity: ProcessAffinity): String = affinity match {
    case ProcessAffinity.Browser  => "BrowserFacade"
    case ProcessAffinity.Renderer => "RendererFacade"
  }

  def emit(
      spec: FacadeSpec,
      facadeByCefStruct: Map[String, String] = Map.empty,
      affinityByCefStruct: Map[String, ProcessAffinity] = Map.empty,
      refs: MessageRefs = MessageRefs.Named
  )(using Naming.Context, Banners): String = {
    val pkg     = spec.packageName
    val cls     = spec.className
    val ctor    = renderConstructor(spec)
    val methods =
      spec.methods.map(m => renderMethod(spec, m, facadeByCefStruct, affinityByCefStruct, refs)).mkString("\n\n")

    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |package $pkg;
       |
       |${FacadeImports.mkString("\n")}
       |
       |/**
       | * Typed facade for {@code ${spec.cefStructName}}, dispatching through a {@link CefSession}.
       | * Each instance is a thin wrapper around a {@link RemoteHandle} that points at a runtime-server-side
       | * ref-counted CEF object.
       | */
       |${Banners.javaGeneratedAnnotation}
       |public final class $cls extends ${baseName(spec.affinity)} {
       |
       |$ctor
       |
       |$methods
       |}
       |""".stripMargin
  }

  def emitBase(affinity: ProcessAffinity, pkg: String, refs: MessageRefs = MessageRefs.Named)(using Banners): String = {
    val isRenderer = affinity == ProcessAffinity.Renderer
    val cls        = baseName(affinity)
    val side       = affinity.toString.toLowerCase
    val (frameField, frameParam, frameAssign, frameAccessor, requestName, requestArgs, responseName) =
      if (isRenderer)
        (
          "    protected final RemoteHandle frame;\n",
          "RemoteHandle frame, ",
          "        this.frame = frame;\n",
          """
            |    public final RemoteHandle frame() {
            |        return frame;
            |    }
            |""".stripMargin,
          "RendererReleaseHandleRequest",
          "frame, handle, cefStructName",
          "RendererReleaseHandleResponse"
        )
      else
        (
          "",
          "",
          "",
          "",
          "ReleaseHandleRequest",
          "handle, cefStructName",
          "ReleaseHandleResponse"
        )
    val requestId       = refs.idExpr(requestName)
    val request         = refs.newExpr(requestName, requestArgs)
    val responseDecoder = refs.decoderExpr(responseName)
    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |package $pkg;
       |
       |import java.util.concurrent.CompletableFuture;
       |${Banners.javaAnnotationImport}
       |import net.kurobako.cef4j.ipc.session.CefFutures;
       |import net.kurobako.cef4j.ipc.session.CefSession;
       |import net.kurobako.cef4j.ipc.session.RemoteFacade;
       |import net.kurobako.cef4j.ipc.session.RemoteHandle;
       |
       |/** Releases the handle of a $side-side facade through the $side release message. */
       |${Banners.javaGeneratedAnnotation}
       |public abstract class $cls extends RemoteFacade {
       |
       |$frameField    private final String cefStructName;
       |
       |    protected $cls(CefSession session, $frameParam RemoteHandle handle, String cefStructName) {
       |        super(session, handle);
       |$frameAssign        this.cefStructName = cefStructName;
       |    }
       |$frameAccessor
       |    @Override
       |    protected final CompletableFuture<Void> release() {
       |        return CefFutures.discard(session.request($requestId, $request, $responseDecoder));
       |    }
       |}
       |""".stripMargin
  }

  private val FacadeImports = List(
    "import java.util.concurrent.CompletableFuture;",
    Banners.javaAnnotationImport,
    "import net.kurobako.cef4j.ipc.session.CefFutures;",
    "import net.kurobako.cef4j.ipc.session.CefSession;",
    "import net.kurobako.cef4j.ipc.session.RemoteHandle;"
  )

  private def renderConstructor(spec: FacadeSpec): String =
    if (spec.affinity == ProcessAffinity.Renderer)
      s"""    public ${spec.className}(CefSession session, RemoteHandle frame, RemoteHandle handle) {
         |        super(session, frame, handle, "${spec.cefStructName}");
         |    }""".stripMargin
    else
      s"""    public ${spec.className}(CefSession session, RemoteHandle handle) {
         |        super(session, handle, "${spec.cefStructName}");
         |    }""".stripMargin

  private def renderMethod(
      facade: FacadeSpec,
      m: FacadeMethod,
      facadeByCefStruct: Map[String, String],
      affinityByCefStruct: Map[String, ProcessAffinity],
      refs: MessageRefs
  )(using Naming.Context): String = {
    val frameLead            = if (facade.affinity == ProcessAffinity.Renderer) List("frame") else Nil
    val ctorArgs             = (frameLead ++ ("handle" :: m.explicitParams.map(_.name))).mkString(", ")
    val (returnType, mapper) = m.resultField match {
      case None    => ("CompletableFuture<Void>", "")
      case Some(f) =>
        f.ty match {
          case FieldType.RemoteHandle =>
            m.handleStructByField.get("result").flatMap(facadeByCefStruct.get) match {
              case Some(facadeCls) =>
                val childAffinity = m.handleStructByField
                  .get("result")
                  .flatMap(affinityByCefStruct.get)
                  .getOrElse(ProcessAffinity.Browser)
                val frameExprForChild: Option[String] =
                  if (childAffinity != ProcessAffinity.Renderer) None
                  else if (facade.affinity == ProcessAffinity.Renderer) Some("frame")
                  else if (facade.cefStructName == "cef_frame_t") Some("handle")
                  else None
                if (childAffinity == ProcessAffinity.Renderer && frameExprForChild.isEmpty) {
                  rawHandleResult(m, f, refs)
                } else {
                  val childCtor = frameExprForChild match {
                    case Some(frameExpr) => s"new $facadeCls(session, $frameExpr, __r.${f.name}())"
                    case None            => s"new $facadeCls(session, __r.${f.name}())"
                  }
                  (s"CompletableFuture<$facadeCls>", s"__r -> $childCtor")
                }
              case None =>
                rawHandleResult(m, f, refs)
            }
          case _ =>
            (s"CompletableFuture<${boxedType(f.ty)}>", s"${refs.typeName(m.responseClassName)}::${f.name}")
        }
    }
    val paramAnnots = m.explicitParams.map(p => s"${JavaEmitter.javaType(p.ty)} ${p.name}").mkString(", ")
    val methodDoc   =
      if (m.javadoc.nonEmpty) m.javadoc.linesIterator.mkString("\n") + "\n"
      else s"""    /** Dispatches {@code ${m.cefMethodName}} to the runtime server. */
              |""".stripMargin
    val request =
      s"session.request(${refs.idExpr(m.requestClassName)}, ${refs.newExpr(m.requestClassName, ctorArgs)}, " +
        s"${refs.decoderExpr(m.responseClassName)})"
    val body =
      if (mapper.isEmpty) s"CefFutures.discard($request)"
      else s"CefFutures.map(\n            $request,\n            $mapper)"
    s"""$methodDoc    public $returnType ${m.methodName}($paramAnnots) {
       |        return $body;
       |    }""".stripMargin
  }

  private def rawHandleResult(m: FacadeMethod, f: FieldSpec, refs: MessageRefs): (String, String) =
    ("CompletableFuture<RemoteHandle>", s"${refs.typeName(m.responseClassName)}::${f.name}")

  private def boxedType(ty: FieldType)(using Naming.Context): String = ty match {
    case FieldType.I32                 => "Integer"
    case FieldType.I64                 => "Long"
    case FieldType.Bool                => "Boolean"
    case FieldType.Utf8String          => "String"
    case FieldType.Bytes               => "byte[]"
    case FieldType.StringList          => "String[]"
    case FieldType.RemoteHandle        => "RemoteHandle"
    case FieldType.DataStruct(cefName) => Naming.sharedTypeName(cefName)
  }
}
