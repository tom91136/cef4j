package net.kurobako.cef4j.codegen.ipc

import net.kurobako.cef4j.codegen.Banners
import net.kurobako.cef4j.codegen.Naming

object JavaDataCodecEmitter {

  def emit(spec: DataStructSpec)(using Naming.Context, Banners): String = {
    val layout = spec.shared.getOrElse(throw IllegalArgumentException(s"${spec.cefStructName} has no shared type"))
    val cls    = SpecDeriver.codecName(spec.cefStructName)
    val pairs  = spec.fields.zip(layout.members)
    val ty     = layout.javaType

    val fixed    = spec.fields.map(f => JavaEmitter.fixedSize(f.ty)).sum
    val strings  = pairs.collect { case (_, m) if m.kind == MemberKind.Str => s"utf8(v.${m.javaName}).length" }
    val size     = (fixed.toString +: strings).mkString(" + ")
    val suppress =
      if (strings.isEmpty) "    @SuppressWarnings(\"SameReturnValue\")\n" else ""

    val encode = pairs.map { case (_, m) => encodeStatement(m) }.mkString("\n")
    val decode = pairs.map { case (_, m) => decodeStatement(m) }.mkString("\n")
    val args   = pairs.collect { case (_, m) if m.kind != MemberKind.WireSize => m.javaName }.mkString(", ")
    val helper =
      if (strings.isEmpty) ""
      else
        """
          |    private static byte[] utf8(@Nullable String value) {
          |        return value == null ? new byte[0] : value.getBytes(StandardCharsets.UTF_8);
          |    }
          |""".stripMargin

    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |package ${spec.packageName};
       |
       |import java.nio.ByteBuffer;
       |import java.nio.charset.StandardCharsets;
       |${Banners.javaAnnotationImport}
       |import net.kurobako.cef4j.ipc.session.WireDecoder;
       |import net.kurobako.cef4j.ipc.session.WireEncoder;
       |import org.jspecify.annotations.Nullable;
       |
       |/** Wire codec for {@link $ty}, which mirrors {@code ${spec.cefStructName}}. */
       |${Banners.javaGeneratedAnnotation}
       |public final class $cls {
       |
       |    private $cls() {}
       |
       |$suppress    public static int encodedSize($ty v) {
       |        return $size;
       |    }
       |
       |    public static void encode(ByteBuffer dst, $ty v) {
       |        WireEncoder.littleEndian(dst, __out -> {
       |$encode
       |        });
       |    }
       |
       |    /** Reads in place from {@code __buf}, advancing its position. The caller has set little-endian order. */
       |    public static $ty decode(ByteBuffer __buf) {
       |$decode
       |        return new $ty($args);
       |    }
       |$helper}
       |""".stripMargin
  }

  private def encodeStatement(m: SharedMember): String = {
    val v = s"v.${m.javaName}"
    val s = m.kind match {
      case MemberKind.I32 | MemberKind.Char => s"__out.putInt($v);"
      case MemberKind.EnumOf(_)             => s"__out.putInt($v == null ? 0 : (int) $v.value);"
      case MemberKind.I64                   => s"__out.putLong($v);"
      case MemberKind.WireSize              => "__out.putLong(0L);"
      case MemberKind.Bool                  => s"WireEncoder.bool(__out, $v);"
      case MemberKind.Str                   => s"WireEncoder.bytes(__out, utf8($v));"
    }
    s"            $s"
  }

  private def decodeStatement(m: SharedMember): String = {
    val n    = m.javaName
    val read = (reader: String) => s"WireDecoder.$reader(__buf, \"$n\")"
    m.kind match {
      case MemberKind.I32            => s"        final int $n = ${read("int32")};"
      case MemberKind.Char           => s"        final char $n = (char) ${read("int32")};"
      case MemberKind.EnumOf(enumTy) => s"        final $enumTy $n = $enumTy.of(${read("int32")});"
      case MemberKind.I64            => s"        final long $n = ${read("int64")};"
      case MemberKind.Bool           => s"        final boolean $n = ${read("bool")};"
      case MemberKind.Str            => s"        final String $n = ${read("utf8")};"
      case MemberKind.WireSize       => s"        ${read("int64")};"
    }
  }
}
