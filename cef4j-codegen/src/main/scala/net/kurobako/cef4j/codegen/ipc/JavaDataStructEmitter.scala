package net.kurobako.cef4j.codegen.ipc

import net.kurobako.cef4j.codegen.Banners
import net.kurobako.cef4j.codegen.Naming

object JavaDataStructEmitter {

  def emit(spec: DataStructSpec)(using Naming.Context, Banners): String = {
    val pkg          = spec.packageName
    val cls          = spec.className
    val importsBlock = renderImports
    val ctor         = renderCtor(spec)
    val getters      = spec.fields.map(renderGetter(_)).mkString("\n\n")
    val sizeBody     = renderSizeBody(spec)
    val sizeSuppress =
      if (spec.fields.exists(_.ty == FieldType.Utf8String)) ""
      else "    @SuppressWarnings(\"SameReturnValue\")\n"
    val encodeBody = renderEncodeBody(spec)
    val decodeBody = renderDecodeBody(spec)
    val builder    = renderBuilder(spec)

    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |package $pkg;
       |
       |$importsBlock
       |
       |/**
       | * Wire-format value type mirroring {@code ${spec.cefStructName}}. Fields are immutable; pass instances
       | * to facade methods (or factory requests) that take this struct. The dispatcher decodes them on the
       | * runtime-server side and fills the matching {@code ${spec.cefStructName}} before invoking CEF.
       | */
       |${Banners.javaGeneratedAnnotation}
       |public final class $cls {
       |
       |${spec.fields.map(renderField(_)).mkString("\n")}
       |
       |$ctor
       |
       |$getters
       |
       |$sizeSuppress    public int encodedSize() {
       |        return $sizeBody;
       |    }
       |
       |    public void encodeInto(ByteBuffer dst) {
       |        final ByteOrder originalOrder = dst.order();
       |        try {
       |            dst.order(ByteOrder.LITTLE_ENDIAN);
       |$encodeBody
       |        } finally {
       |            dst.order(originalOrder);
       |        }
       |    }
       |
       |    /** Reads in place from {@code __buf}, advancing its position. Caller must have set
       |      * {@link ByteOrder#LITTLE_ENDIAN} on the buffer (the standalone {@code decode(payload)} entry point
       |      * below does that for you). For nested use inside a parent message's decoder the parent has already
       |      * configured the buffer.
       |      */
       |    public static $cls decode(ByteBuffer __buf) {
       |$decodeBody
       |        return new $cls(${spec.fields.map(_.name).mkString(", ")});
       |    }
       |
       |    public static Builder builder() {
       |        return new Builder();
       |    }
       |
       |$builder
       |}
       |""".stripMargin
  }

  private def renderBuilder(spec: DataStructSpec)(using Naming.Context): String = {
    val cls     = spec.className
    val bFields = spec.fields.map { f =>
      val ty   = JavaEmitter.fullyQualifiedJavaType(f.ty)
      val init = defaultValue(f.ty).fold("")(v => s" = $v")
      s"        private $ty ${f.name}$init;"
    }.mkString("\n")
    val setters   = spec.fields.map(renderSetter(_)).mkString("\n\n")
    val buildArgs = spec.fields.map(_.name).mkString(", ")
    s"""    /** Lombok-style builder. */
       |    public static final class Builder {
       |
       |$bFields
       |
       |$setters
       |
       |        public $cls build() {
       |            return new $cls($buildArgs);
       |        }
       |    }""".stripMargin
  }

  private def renderSetter(f: FieldSpec)(using Naming.Context): String = {
    val annot = f.ty match {
      case FieldType.Utf8String | FieldType.Bytes | FieldType.RemoteHandle | FieldType.DataStruct(_) =>
        ""
      case _ => ""
    }
    s"""        public Builder ${f.name}($annot${JavaEmitter.fullyQualifiedJavaType(f.ty)} value) {
       |            this.${f.name} = value;
       |            return this;
       |        }""".stripMargin
  }

  private def defaultValue(ty: FieldType): Option[String] = ty match {
    case FieldType.I32 | FieldType.I64 | FieldType.Bool => None
    case FieldType.Utf8String                           => Some("\"\"")
    case FieldType.Bytes                                => Some("new byte[0]")
    case FieldType.StringList   => Some("new String[0]") // unreachable; data structs don't carry StringLists
    case FieldType.RemoteHandle => Some("net.kurobako.cef4j.ipc.session.RemoteHandle.NULL")
    case FieldType.DataStruct(_) => None // builder forces explicit set; null reaches Nonnull-annotated ctor
  }

  private def renderImports: String =
    s"""import java.nio.ByteBuffer;
      |import java.nio.ByteOrder;
      |import java.nio.charset.StandardCharsets;
      |${Banners.javaAnnotationImport}
      |import net.kurobako.cef4j.ipc.session.WireDecoder;""".stripMargin

  private def renderField(f: FieldSpec)(using Naming.Context): String =
    s"    private final ${JavaEmitter.fullyQualifiedJavaType(f.ty)} ${f.name};"

  private def renderCtor(spec: DataStructSpec)(using Naming.Context): String = {
    val params = spec.fields.map { f =>
      paramAnnotation(f.ty) + JavaEmitter.fullyQualifiedJavaType(f.ty) + " " + f.name
    }.mkString(", ")
    val assigns = spec.fields.map(f => s"        this.${f.name} = ${f.name};").mkString("\n")
    s"""    public ${spec.className}($params) {
       |$assigns
       |    }""".stripMargin
  }

  private def renderGetter(f: FieldSpec)(using Naming.Context): String = {
    val annot = nonnullPrefix(f.ty)
    s"""$annot    public ${JavaEmitter.fullyQualifiedJavaType(f.ty)} ${f.name}() {
       |        return ${f.name};
       |    }""".stripMargin
  }

  private def renderSizeBody(spec: DataStructSpec): String = {
    val fixed    = spec.fields.map(f => JavaEmitter.fixedSize(f.ty)).sum
    val variable = spec.fields.collect {
      case FieldSpec(name, FieldType.Utf8String) => s"$name.getBytes(StandardCharsets.UTF_8).length"
    }
    if (variable.isEmpty) s"$fixed"
    else if (fixed == 0) variable.mkString(" + ")
    else (fixed.toString +: variable).mkString(" + ")
  }

  private def renderEncodeBody(spec: DataStructSpec): String =
    spec.fields.map { f =>
      f.ty match {
        case FieldType.I32        => s"            dst.putInt(${f.name});"
        case FieldType.I64        => s"            dst.putLong(${f.name});"
        case FieldType.Bool       => s"            dst.put((byte) (${f.name} ? 1 : 0));"
        case FieldType.Utf8String =>
          s"""            final byte[] ${f.name}Bytes = ${f.name}.getBytes(StandardCharsets.UTF_8);
             |            dst.putInt(${f.name}Bytes.length);
             |            dst.put(${f.name}Bytes);""".stripMargin
        case FieldType.Bytes         => s"            dst.putInt(${f.name}.length); dst.put(${f.name});"
        case FieldType.StringList    => "            // StringList unreachable in DataStruct" // unreachable
        case FieldType.RemoteHandle  => s"            dst.putInt(${f.name}.id());"
        case FieldType.DataStruct(_) => s"            ${f.name}.encodeInto(dst);"
      }
    }.mkString("\n")

  private def renderDecodeBody(spec: DataStructSpec)(using Naming.Context): String =
    spec.fields.map(JavaEmitter.decodeRead(_, qualified = true)).mkString("\n")

  private def paramAnnotation(ty: FieldType): String = ty match {
    case FieldType.Utf8String | FieldType.Bytes | FieldType.StringList | FieldType.RemoteHandle |
        FieldType.DataStruct(_) =>
      ""
    case _ => ""
  }

  private def nonnullPrefix(ty: FieldType): String = ty match {
    case FieldType.Utf8String | FieldType.Bytes | FieldType.StringList | FieldType.RemoteHandle |
        FieldType.DataStruct(_) =>
      ""
    case _ => ""
  }
}
