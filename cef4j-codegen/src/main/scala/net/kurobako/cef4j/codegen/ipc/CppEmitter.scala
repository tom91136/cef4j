package net.kurobako.cef4j.codegen.ipc

import net.kurobako.cef4j.codegen.Naming

object CppEmitter {

  def emit(spec: MessageSpec, exactPayload: Boolean = true)(using Naming.Context): String = {
    val ns       = spec.packageName.replace('.', '_').toLowerCase
    val cls      = spec.className
    val fields   = renderFields(spec)
    val sizeBody = renderEncodedSizeBody(spec)
    val encBody  = renderEncodeBody(spec)
    val decBody  = renderDecodeBody(spec)
    val reader   = if (spec.fields.isEmpty && !exactPayload) "[[maybe_unused]] cef4j::wire::Reader reader"
    else "cef4j::wire::Reader reader"
    val exhaustion     = if (exactPayload) "\n        reader.finish();" else ""
    val nestedIncludes = spec.fields.collect {
      case FieldSpec(_, FieldType.DataStruct(cefName)) => SpecDeriver.cefStructToClassName(cefName)
    }.distinct.map(c => s"""#include "$c.h"""").mkString("\n")

    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |#pragma once
       |
       |#include <cstdint>
       |#include <string>
       |#include <vector>
       |
       |#include "Wire.h"
       |$nestedIncludes
       |
       |namespace $ns {
       |
       |struct $cls {
       |    static constexpr int32_t MessageId = ${spec.messageId};
       |
       |$fields
       |    /** Number of payload bytes that {@link encodeInto} writes for this instance. */
       |    size_t encodedSize() const noexcept {
       |        return $sizeBody;
       |    }
       |
       |    /** Writes exactly {@link encodedSize} bytes starting at {@code dst}. */
       |    void encodeInto(uint8_t* dst) const noexcept {
       |$encBody
       |    }
       |
       |    /** Reads a $cls from a payload starting at {@code src}; {@code len} bounds the buffer. */
       |    static $cls decode(const uint8_t* src, size_t len) {
       |        $reader(src, len, "$cls");
       |        $cls out;
       |$decBody$exhaustion
       |        return out;
       |    }
       |};
       |
       |} // namespace $ns
       |""".stripMargin
  }

  private def cppType(ty: FieldType)(using Naming.Context): String = ty match {
    case FieldType.I32                 => "int32_t"
    case FieldType.I64                 => "int64_t"
    case FieldType.Bool                => "bool"
    case FieldType.Utf8String          => "std::string"
    case FieldType.Bytes               => "std::vector<uint8_t>"
    case FieldType.StringList          => "std::vector<std::string>"
    case FieldType.RemoteHandle        => "int32_t" // resolved via runtime-server-side HandleTable
    case FieldType.DataStruct(cefName) => SpecDeriver.cefStructToClassName(cefName)
  }

  private def renderFields(spec: MessageSpec)(using Naming.Context): String =
    spec.fields.map { f =>
      val init = f.ty match {
        case FieldType.I32 | FieldType.I64 | FieldType.RemoteHandle => " = 0"
        case FieldType.Bool                                         => " = false"
        case _                                                      => ""
      }
      s"    ${cppType(f.ty)} ${f.name}$init;"
    }.mkString("\n") + "\n"

  private def fixedSize(ty: FieldType): Int = ty match {
    case FieldType.I32 | FieldType.RemoteHandle => 4
    case FieldType.I64                          => 8
    case FieldType.Bool                         => 1
    case FieldType.Utf8String | FieldType.Bytes => 4
    case FieldType.StringList                   => 0
    case FieldType.DataStruct(_)                => 0
  }

  private def variableSizeExpr(field: FieldSpec): Option[String] = field.ty match {
    case FieldType.Utf8String | FieldType.Bytes => Some(s"${field.name}.size()")
    case FieldType.StringList                   => Some(s"cef4j::wire::encodedSize(${field.name})")
    case FieldType.DataStruct(_)                => Some(s"${field.name}.encodedSize()")
    case _                                      => None
  }

  private def renderEncodedSizeBody(spec: MessageSpec): String = {
    val fixed    = spec.fields.map(f => fixedSize(f.ty)).sum
    val variable = spec.fields.flatMap(variableSizeExpr).mkString(" + ")
    if (variable.isEmpty) fixed.toString else s"$fixed + $variable"
  }

  private def wireOp(ty: FieldType): String = ty match {
    case FieldType.I32 | FieldType.RemoteHandle => "i32"
    case FieldType.I64                          => "i64"
    case FieldType.Bool                         => "boolean"
    case FieldType.Utf8String                   => "string"
    case FieldType.Bytes                        => "bytes"
    case FieldType.StringList                   => "strings"
    case FieldType.DataStruct(_)                => "nested"
  }

  private def renderEncodeBody(spec: MessageSpec): String =
    if (spec.fields.isEmpty) "        (void)dst;"
    else
      ("        cef4j::wire::Writer writer(dst);" :: spec.fields.map(f =>
        s"        writer.${wireOp(f.ty)}(this->${f.name});"
      )).mkString("\n")

  private def renderDecodeBody(spec: MessageSpec)(using Naming.Context): String =
    spec.fields.map { f =>
      val read = f.ty match {
        case FieldType.DataStruct(cefName) => s"nested<${SpecDeriver.cefStructToClassName(cefName)}>"
        case other                         => wireOp(other)
      }
      s"""        out.${f.name} = reader.$read("${f.name}");"""
    }.mkString("\n")
}
