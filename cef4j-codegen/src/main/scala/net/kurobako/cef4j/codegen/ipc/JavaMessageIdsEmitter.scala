package net.kurobako.cef4j.codegen.ipc

import net.kurobako.cef4j.codegen.Banners

object JavaMessageIdsEmitter {

  def emit(ids: List[MessageId], packageName: String)(using Banners): String = {
    val constants = ids.map(id => s"    public static final int ${id.constant} = ${id.value};").mkString("\n")
    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |package $packageName;
       |
       |${Banners.javaAnnotationImport}
       |
       |/** Wire message ids of every protocol message. */
       |${Banners.javaGeneratedAnnotation}
       |public final class ${MessageId.ClassName} {
       |
       |    private ${MessageId.ClassName}() {}
       |
       |$constants
       |}
       |""".stripMargin
  }
}
