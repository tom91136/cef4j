package net.kurobako.cef4j.codegen.ipc

import net.kurobako.cef4j.codegen.Banners
import net.kurobako.cef4j.codegen.Naming

object JavaHandlerEmitter {

  def emit(spec: HandlerSpec)(using Naming.Context, Banners): String = {
    val pkg     = spec.packageName
    val cls     = spec.className
    val methods = spec.methods.map(renderInterfaceMethod(_)).mkString("\n\n")
    val ons     = spec.methods.flatMap(renderRegistration(_)).mkString(",\n")

    s"""// Generated by net.kurobako.cef4j.codegen.ipc - do not edit by hand.
       |package $pkg;
       |
       |${Banners.javaAnnotationImport}
       |import net.kurobako.cef4j.ipc.session.CefSession;
       |import net.kurobako.cef4j.policy.NullableBoundary;
       |
       |/**
       | * Typed handler interface for {@code ${spec.cefStructName}}. Each method maps to a callback CEF would
       | * fire on this struct; default empty bodies let implementers override only the events they want.
       | *
       | * <p>Use {@link #register(CefSession, $cls)} to bind every method to its corresponding wire event in
       | * one step. Close the returned registration to unsubscribe every method.
       | */
       |${Banners.javaGeneratedAnnotation}
       |@NullableBoundary("generated CEF callback contract")
       |public interface $cls {
       |
       |$methods
       |
       |    /** Registers {@code handler} for every event this interface declares. */
       |    static CefSession.HandlerRegistration register(CefSession session, $cls handler) {
       |        return CefSession.HandlerRegistration.combine(
       |$ons);
       |    }
       |}
       |""".stripMargin
  }

  private def renderInterfaceMethod(m: HandlerMethod)(using Naming.Context): String = {
    val params = m.params
      .map(p => s"${JavaEmitter.fullyQualifiedJavaType(p.ty)} ${p.name}")
      .mkString(", ")
    val callback = SpecDeriver.camelToSnake(m.methodName)
    m.returnType match {
      case None =>
        val doc = methodDoc(m, s"Mirrors the {@code $callback} callback on the CEF struct.")
        s"$doc${voidDefaultMethod(m, params)}"
      case Some(FieldType.Bool) =>
        // Empty means no JVM opinion and maps to CEF's false default.
        optionalDefaultMethod(m, params, callback, "java.util.Optional<Boolean>", "java.util.Optional.empty()")
      case Some(FieldType.I32) =>
        optionalDefaultMethod(m, params, callback, "java.util.OptionalInt", "java.util.OptionalInt.empty()")
      case Some(_) =>
        voidDefaultMethod(m, params)
    }
  }

  private def voidDefaultMethod(m: HandlerMethod, params: String): String =
    s"""    @SuppressWarnings("EmptyMethod")
       |    default void ${m.methodName}($params) {}""".stripMargin

  private def optionalDefaultMethod(
      m: HandlerMethod,
      params: String,
      callback: String,
      returnType: String,
      empty: String
  ): String = {
    val doc = methodDoc(
      m,
      s"Mirrors the {@code $callback} callback. An empty result selects CEF's default behavior."
    )
    s"""$doc    @SuppressWarnings("SameReturnValue")
       |    default $returnType ${m.methodName}($params) { return $empty; }""".stripMargin
  }

  private def methodDoc(m: HandlerMethod, fallback: String): String =
    if (m.javadoc.nonEmpty) m.javadoc.linesIterator.mkString("\n") + "\n"
    else s"""    /** $fallback */
            |""".stripMargin

  private def renderRegistration(m: HandlerMethod): Option[String] = {
    val args = m.params.map(p => s"ev.${p.name}()").mkString(", ")
    m.returnType match {
      case None =>
        val subscription =
          if (m.eventClassName == "LifeSpanHandlerOnAfterCreatedEvent") "onLatest" else "on"
        Some(s"""                session.$subscription(${m.eventClassName}.MESSAGE_ID, ${m.eventClassName}.DECODER,
                |                        ev -> handler.${m.methodName}($args))""".stripMargin)
      case Some(FieldType.Bool) =>
        val respCls = m.responseClassName.getOrElse(m.eventClassName + "Response")
        intercept(m, args, "java.util.Optional<Boolean>", s"java.util.Optional.of(new $respCls(answer.orElse(false)))")
      case Some(FieldType.I32) =>
        val respCls = m.responseClassName.getOrElse(m.eventClassName + "Response")
        intercept(m, args, "java.util.OptionalInt", s"answer.stream().mapToObj($respCls::new).findFirst()")
      case Some(_) =>
        None
    }
  }

  private def intercept(
      m: HandlerMethod,
      args: String,
      boxedType: String,
      response: String
  ): Option[String] =
    Some(s"""                session.intercept(${m.eventClassName}.MESSAGE_ID, ${m.eventClassName}.DECODER, ev -> {
             |                    final $boxedType answer = handler.${m.methodName}($args);
             |                    return $response;
             |                })""".stripMargin)
}
